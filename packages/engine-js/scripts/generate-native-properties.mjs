// Generates src/native-properties.ts from the Rust native CSS property registry, so
// both engines append the same built-in native declaration utilities.
//
//   node packages/engine-js/scripts/generate-native-properties.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..')
const source = readFileSync(join(root, 'crates/mastercss-schema/src/native-properties.rs'), 'utf8')
const names = source.slice(source.indexOf('NATIVE_CSS_PROPERTY_NAMES'), source.indexOf('NATIVE_CSS_PROPERTY_ENDS'))
  .match(/^\s+"([^"]+)",$/gm)
  .map((line) => line.trim().slice(1, -2))
if (names.some((name) => name.includes(' '))) throw new Error('A native property name contains a space.')
if (names.some((name, index) => index && names[index - 1] >= name)) throw new Error('Native property names are not in byte order.')
// Front coding: each entry is the length of the prefix it shares with the previous name, as one
// character from `0`, then the rest of the name. The registry is sorted, so this halves the bundle text.
let previous = ''
const entries = names.map((name) => {
  let shared = 0
  while (shared < previous.length && previous[shared] === name[shared]) shared++
  if (shared > 42) throw new Error(`A shared prefix of ${shared} characters does not fit one character.`)
  previous = name
  return String.fromCharCode(48 + shared) + name.slice(shared)
})
let decoded = ''
if (entries.map((entry) => decoded = decoded.slice(0, entry.charCodeAt(0) - 48) + entry.slice(1)).join(' ') !== names.join(' ')) {
  throw new Error('Front-coded native properties do not decode to the registry.')
}
writeFileSync(join(root, 'packages/engine-js/src/native-properties.ts'), [
  '// Generated by scripts/generate-native-properties.mjs from crates/mastercss-schema. Do not edit.',
  '',
  'let previous = \'\'',
  '',
  '/**',
  ' * The native CSS property registry in byte order, including the `--*` entry. Each entry is front coded: the',
  ' * length of the prefix it shares with the previous name, as one character from `0`, then the rest.',
  ' */',
  `export const NATIVE_CSS_PROPERTIES: readonly string[] = ${JSON.stringify(entries.join(' '))}.split(' ')`,
  '  .map((entry) => previous = previous.slice(0, entry.charCodeAt(0) - 48) + entry.slice(1))',
  '',
  'export const NATIVE_CSS_PROPERTY_SET: ReadonlySet<string> = new Set(NATIVE_CSS_PROPERTIES)',
  ''
].join('\n'))
process.stdout.write(`${names.length} native properties\n`)
