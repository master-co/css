// Generates src/native-properties.ts from the Rust native CSS property registry, so
// both engines append the same built-in native declaration utilities.
//
//   node packages/engine-js/scripts/generate-native-properties.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..')
const source = readFileSync(join(root, 'crates/mastercss-schema/src/native-properties.rs'), 'utf8')
const names = source.slice(source.indexOf('NATIVE_CSS_PROPERTY_NAMES'), source.indexOf('NATIVE_CSS_PROPERTY_ENDS'))
  .match(/^\s+"([^"]+)",$/gm)
  .map((line) => line.trim().slice(1, -2))
if (names.some((name) => name.includes(' '))) throw new Error('A native property name contains a space.')
writeFileSync(join(root, 'packages/engine-js/src/native-properties.ts'), [
  '// Generated by scripts/generate-native-properties.mjs from crates/mastercss-schema. Do not edit.',
  '',
  '/** The native CSS property registry in byte order, including the `--*` entry. */',
  `export const NATIVE_CSS_PROPERTIES: readonly string[] = ${JSON.stringify(names.join(' '))}.split(' ')`,
  ''
].join('\n'))
process.stdout.write(`${names.length} native properties\n`)
