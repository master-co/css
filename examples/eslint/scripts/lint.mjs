import assert from 'node:assert/strict'
import { relative } from 'node:path'
import { ESLint } from 'eslint'

const eslint = new ESLint()
const results = await eslint.lintFiles(['.'])
const errors = results.flatMap(result => result.messages.filter(message => message.severity === 2).map(message => ({
  file: relative(process.cwd(), result.filePath).replaceAll('\\', '/'),
  rule: message.ruleId,
  message: message.message
})))
const invalid = (file, className) => ({
  file: `src/${file}.html`,
  rule: '@master/css/no-invalid-classes',
  message: `Unknown Master CSS class "${className}". It is not generated by the active manifest.`
})
const expected = [invalid('know', 'btn'), invalid('know', 'unknow'), invalid('validation', 'font:')]
const sort = values => values.toSorted((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b)))
assert.deepEqual(sort(errors), sort(expected), 'Lint examples must produce exactly their documented errors, with no unexpected errors')
console.log(`Verified ${results.length} example files and ${expected.length} intentional invalid-class diagnostics.`)
