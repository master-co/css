                    import { StyleSheet } from '@master/css';
                    
                    export default function MyDocument() {
                        return (
                            <Html>
                                <Head/>
                                <body>
                                    <Main/>
                                    <NextScript/>
                                </body>
                            </Html>
                        )
                    }
                    
