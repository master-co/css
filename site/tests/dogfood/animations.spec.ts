test('native play-state controls retain keyboard operation, resume time and actual hover/focus selectors', async ({ page, browserName }) => {
  await page.goto('/en/reference/animation-play-state')
  const base = await scene(page, 'animation-play-state', 'run-an-animation'), input = base.getByRole('checkbox', { name: 'Run indicator' })
  await expect(target(base)).toHaveCSS('animation-play-state', 'paused')
  await input.focus(); await page.keyboard.press('Space')
  await expect(target(base)).toHaveCSS('animation-play-state', 'running')
  await expect.poll(() => time(target(base))).toBeGreaterThan(150)
  await page.keyboard.press('Space'); await expect(target(base)).toHaveCSS('animation-play-state', 'paused')
  const held = await time(target(base))
  await input.check(); await expect.poll(() => time(target(base))).toBeGreaterThan(held + 80)
  const hover = await scene(page, 'animation-play-state', 'pause-animation')
  await hover.getByRole('checkbox').check(); await page.mouse.move(0, 0)
  await expect(target(hover)).toHaveCSS('animation-play-state', 'running')
  if (await page.evaluate(() => matchMedia('(hover:hover)').matches)) {
    await hover.getByText('Hover this panel to pause').hover()
    await expect(target(hover)).toHaveCSS('animation-play-state', 'paused')
    await page.mouse.move(0, 0); await expect(target(hover)).toHaveCSS('animation-play-state', 'running')
  }
  const editor = await scene(page, 'animation-play-state', 'pause-nonessential-motion')
  await editor.getByRole('checkbox').check(); await expect(target(editor)).toHaveCSS('animation-play-state', 'running')
  const field = editor.getByRole('textbox', { name: 'Project name' })
  await field.focus(); await field.fill('New canvas'); await expect(field).toHaveValue('New canvas')
  await expect(target(editor)).toHaveCSS('animation-play-state', 'paused')
  await editor.getByRole('checkbox').focus(); await expect(target(editor)).toHaveCSS('animation-play-state', 'running')
  const demo = example(page, 'animation-play-state', 'apply-conditionally'), frame = await ready(demo)
  await frame.getByRole('checkbox').check()
  await viewport(demo, 390); await expect(target(frame)).toHaveCSS('animation-play-state', 'paused')
  await viewport(demo, 900); await expect(target(frame)).toHaveCSS('animation-play-state', 'running')
  await page.emulateMedia({ reducedMotion: 'reduce' }); await expect(target(frame)).toHaveCSS('animation-play-state', 'paused')
  await print(page, browserName, target(frame))
  await expect(demo.getByRole('button', { name: 'Replay', exact: true })).toHaveCount(0)
})

