import { expect, test, type FrameLocator, type Locator, type Page } from '@playwright/test'

const routes = ['animation', 'animation-delay', 'animation-direction', 'animation-duration', 'animation-fill-mode', 'animation-iteration-count', 'animation-name', 'animation-play-state', 'animation-timing-function']
const example = (page: Page, route: string, section: string) => page.locator(`[data-demo-case="${route}#${section}"]`)
const target = (frame: FrameLocator, index?: number) => frame.locator(`#${index === undefined ? '' : `example-${index}-`}target`)
async function ready(demo: Locator) {
  await demo.scrollIntoViewIfNeeded()
  await expect(demo.locator('iframe')).toHaveAttribute('data-ready', 'true')
  await demo.locator('iframe').evaluate(async (element: HTMLIFrameElement) => { await element.contentDocument!.fonts.ready })
  return demo.frameLocator('iframe')
}
async function scene(page: Page, route: string, section: string) { return ready(example(page, route, section)) }
async function viewport(demo: Locator, width: number) {
  await demo.getByLabel('Viewport', { exact: true }).fill(String(width))
  await expect.poll(() => demo.locator('iframe').evaluate(e => e.clientWidth)).toBe(width)
}
async function seek(item: Locator, time: number) {
  return item.evaluate(async (e, time) => {
    const animation = e.getAnimations()[0]
    if (!animation) throw new Error('The authored CSS animation is missing')
    animation.pause(); animation.currentTime = time
    await new Promise<void>(resolve => requestAnimationFrame(() => resolve()))
    const style = getComputedStyle(e), matrix = new DOMMatrixReadOnly(style.transform)
    return { x: matrix.e, y: matrix.f, a: matrix.a, b: matrix.b, opacity: Number(style.opacity), progress: animation.effect!.getComputedTiming().progress }
  }, time)
}
async function time(item: Locator) { return item.evaluate(e => Number(e.getAnimations()[0]?.currentTime ?? 0)) }
async function print(page: Page, browserName: string, item: Locator) {
  if (browserName === 'chromium') {
    await page.emulateMedia({ media: 'print' }); await expect(item).toHaveCSS('animation-name', 'none')
    await page.emulateMedia({ media: 'screen' })
  }
}

test('animation shorthand preserves complete SVGs, negative segment phases and custom keyframes', async ({ page, browserName }) => {
  await page.goto('/en/reference/animation')
  const ping = await scene(page, 'animation', 'ping-indicator')
  await expect(ping.getByText('Open for orders')).toBeVisible()
  await expect(ping.locator('circle')).toHaveCount(2)
  await expect(target(ping)).toHaveCSS('animation-name', 'ping')
  const rotated = await scene(page, 'animation', 'rotate-indicator')
  expect((await seek(target(rotated), 250)).b).toBeCloseTo(-1, 2)
  const spinner = await scene(page, 'animation', 'loading-spinner')
  await expect(spinner.locator('path')).toHaveCount(8)
  expect(await spinner.locator('path').evaluateAll(paths => paths.map(e => getComputedStyle(e).animationDelay))).toEqual(['-0.875s', '-0.75s', '-0.625s', '-0.5s', '-0.375s', '-0.25s', '-0.125s', '0s'])
  const custom = await scene(page, 'animation', 'add-your-animations')
  await expect(target(custom)).toHaveCSS('animation-duration', '0.5s')
  expect((await seek(target(custom), 0)).y).toBeCloseTo(40, 1)
  expect((await seek(target(custom), 500)).y).toBeCloseTo(0, 1)
  const demo = example(page, 'animation', 'apply-conditionally'), frame = await ready(demo)
  await viewport(demo, 390); await expect(target(frame)).toHaveCSS('animation-name', 'none')
  await viewport(demo, 900); await expect(target(frame)).toHaveCSS('animation-name', 'rotate')
  await print(page, browserName, target(frame))
})

