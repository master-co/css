import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE_EXTENSIONS = new Set([
  '.cjs', '.cts', '.js', '.jsx', '.mjs', '.mts', '.rs', '.ts', '.tsx'
])
const SUPPORT_PATH = /(?:^|\/)(?:benchmarks?|e2e|fixtures|scripts|tests?|__tests__)(?:\/|$)/u
const SUPPORT_FILE = /(?:\.(?:bench|spec|test)\.[cm]?[jt]sx?$|^crates\/xtask\/templates\/)/u
const GENERATED_MARKER = /generated by .*do not edit directly/is

function extension(path) {
  const match = path.match(/(\.[^.\/]+)$/u)
  return match?.[1] ?? ''
}

function lineCount(text) {
  if (!text.length) return 0
  return text.split(/\r?\n/u).length - (text.endsWith('\n') ? 1 : 0)
}

function isContextFile(path) {
  return path === 'AGENTS.md'
    || path.startsWith('.ai/') && path.endsWith('.md')
    || path.endsWith('/AI.md')
}

function classify(path) {
  if (isContextFile(path)) return 'context'
  if (!SOURCE_EXTENSIONS.has(extension(path))) return null
  if (SUPPORT_PATH.test(path) || SUPPORT_FILE.test(path)) return 'support'
  return 'source'
}

function metric(path, content) {
  const bytes = Buffer.byteLength(content)
  return { path, lines: lineCount(content), bytes }
}

function exceeds(value, limit) {
  return value.lines > limit.maxLines || value.bytes > limit.maxBytes
}

export function evaluateSourceBudgets(files, policy) {
  const exceptions = new Map(policy.exceptions.map((entry) => [entry.path, entry]))
  const seenExceptions = new Set()
  const violations = []
  let checked = 0
  let generated = 0

  for (const file of files) {
    const category = classify(file.path)
    if (!category) continue
    const value = metric(file.path, file.content)
    const exception = exceptions.get(file.path)
    if (exception) {
      seenExceptions.add(file.path)
      if (!exceeds(value, policy.limits[category])) {
        violations.push(`${file.path}: budget exception is stale; the file now fits the ${category} budget.`)
      } else if (value.lines > exception.maxLines || value.bytes > exception.maxBytes) {
        violations.push(`${file.path}: exception ceiling exceeded (${value.lines}/${exception.maxLines} lines, ${value.bytes}/${exception.maxBytes} bytes).`)
      }
      checked++
      continue
    }
    if (category !== 'context' && GENERATED_MARKER.test(file.content.slice(0, 512))) {
      generated++
      continue
    }
    const limit = policy.limits[category]
    if (exceeds(value, limit)) {
      violations.push(`${file.path}: ${category} budget exceeded (${value.lines}/${limit.maxLines} lines, ${value.bytes}/${limit.maxBytes} bytes).`)
    }
    checked++
  }

  for (const exception of policy.exceptions) {
    if (!seenExceptions.has(exception.path)) {
      violations.push(`${exception.path}: budget exception is stale because the file no longer exists or is not checked.`)
    }
  }

  return { checked, generated, exceptions: seenExceptions.size, violations }
}

export function checkRepositorySourceBudgets(root = process.cwd()) {
  const policy = JSON.parse(readFileSync(resolve(root, '.ai/context/source-budget.json'), 'utf8'))
  const paths = execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard'], {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024
  }).split('\0').filter(Boolean)
  const files = paths
    .filter((path) => classify(path) && existsSync(resolve(root, path)))
    .map((path) => ({
    path,
    content: readFileSync(resolve(root, path), 'utf8')
    }))
  return evaluateSourceBudgets(files, policy)
}

function runCLI() {
  const result = checkRepositorySourceBudgets()
  if (result.violations.length) {
    console.error(['AI context budget failed:', ...result.violations.map((violation) => `- ${violation}`)].join('\n'))
    process.exitCode = 1
    return
  }
  console.log(`AI context budget passed for ${result.checked} files (${result.generated} generated excluded, ${result.exceptions} bounded exception).`)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) runCLI()
